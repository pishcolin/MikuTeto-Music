function glyph(token) {
    return G[token] || G[token.toUpperCase()] || G[token.toLowerCase()] || null;
}

// Returns { path: SVG path of pixel runs, width } in item units.
function build(text, px) {
    var x = 0, parts = [];
    var s = String(text || "");
    var i = 0;
    while (i < s.length) {
        var token = s.charAt(i);
        if (token === "{") {
            var close = s.indexOf("}", i);
            if (close > i) { token = s.substring(i, close + 1); i = close; }
        }
        i++;
        var g = glyph(token);
        if (!g) g = G[" "];
        var w = g[0].length;
        for (var row = 0; row < 7; row++) {
            var line = g[row] || "";
            var col = 0;
            while (col < w) {
                if (line.charAt(col) !== "#") { col++; continue; }
                var start = col;
                while (col < w && line.charAt(col) === "#") col++;
                var len = col - start;
                parts.push("M" + (x + start * px) + " " + (row * px) + "h" + (len * px) + "v" + px + "h" + (-len * px) + "z");
            }
        }
        x += (w + 1) * px;
    }
    return { path: parts.join(""), width: Math.max(0, x - px) };
}
